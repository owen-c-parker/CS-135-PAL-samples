# We can store data for later using variables

variable = "You'll need me later..."

# Variables can have multiple types, including but not limited to:
# int : An integer value, a number without any fractional part
#   ex. 4, 13, 0, -999
# float : Short for "floating point", a format that lets you store decimal numbers
#   ex. 3.3, -99.642, 9000.1
# str : A string, a sequence of text characters, surrounded by single (') or double (") quotes
#   ex. "Owen is great", 'Learn Python!', "😃"
# bool : A true or false value
#   ex. True, False

# You can see the type of a variable using the type(var) function

print(variable)